--this makes sure that events cannot be linked to rooms that are not available
CREATE OR REPLACE FUNCTION public.check_event_room()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_capacity  integer;
    v_status text;
BEGIN
    -- No room assigned yet, or the event is dead/archived: nothing to enforce
    IF NEW.r_id IS NULL
       OR NEW.e_status IN ('cancelled')
       OR NEW.e_archived_at IS NOT NULL THEN
        RETURN NEW;
    END IF;

    SELECT r_capacity, r_status
      INTO v_capacity, v_status
      FROM public.room
     WHERE r_id = NEW.r_id;

    IF v_status != 'Available' THEN
        RAISE EXCEPTION 'Room % is unavailable', NEW.r_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.e_attendance > v_capacity THEN
        RAISE EXCEPTION 'Attendance (%) exceeds capacity (%) of room %',
            NEW.e_attendance, v_capacity, NEW.r_id
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER event_room_check
BEFORE INSERT OR UPDATE OF r_id, e_attendance, e_status, e_archived_at
ON public.event
FOR EACH ROW
EXECUTE FUNCTION public.check_event_room();

